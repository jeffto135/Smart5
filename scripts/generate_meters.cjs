const allMeters = [];
let counter = 1;

for (const dist of districts) {
  const [baseLat, baseLng] = dist.center;
  for (let sIdx = 0; sIdx < dist.streets.length; sIdx++) {
    const street = dist.streets[sIdx];
    const numClusters = 3 + (sIdx % 3);
    for (let c = 0; c < numClusters; c++) {
      const idStr = 'HK-MTR-' + String(counter).padStart(5, '0');
      counter++;

      const angle = (sIdx * 0.72) + (c * 1.35);
      const radius = 0.0032 + (sIdx * 0.00065) + (c * 0.00045);
      const lat = Number((baseLat + Math.sin(angle) * radius).toFixed(6));
      const lng = Number((baseLng + Math.cos(angle) * radius).toFixed(6));

      const totalSpaces = 6 + ((counter * 7) % 15);
      // Ensure ~25% of meters have 0 spaces to test the 0 vacancy feature properly!
      const isFull = (counter % 4 === 0);
      const vacantSpaces = isFull ? 0 : Math.max(1, ((counter * 11) % totalSpaces));

      const isShort = (counter % 5 === 0);
      const maxDur = isShort ? '30分鐘' : (counter % 3 === 0 ? '1小時' : '2小時');
      const period = (counter % 4 === 0) 
        ? '全日 08:00 - 24:00' 
        : (counter % 2 === 0)
        ? '星期一至六 08:00 - 24:00 (公眾假期除外)'
        : '星期一至六 08:00 - 24:00；星期日及公眾假期 10:00 - 22:00';

      const segName = c === 0 ? '(近路口)' : c === 1 ? '(中段)' : c === 2 ? '(近交界處)' : '(段 ' + (c + 1) + ')';
      const fullName = dist.district + ' ' + street + ' ' + segName;

      allMeters.push({
        meterId: idStr,
        streetName: fullName,
        district: dist.district,
        region: dist.region,
        lat,
        lng,
        vacantSpaces,
        totalSpaces,
        chargingPeriod: period,
        ratePer15Min: 2.0,
        maxDuration: maxDur,
        paymentMethods: ['八達通', '感應式信用卡', '轉數快', '快易通'],
        lastUpdated: '剛剛更新'
      });
    }
  }
}

console.log('Total parking meters generated:', allMeters.length);
const outPath = 'src/data/parkingMeters.json';
fs.writeFileSync(outPath, JSON.stringify(allMeters));
console.log('Successfully saved to', outPath);
