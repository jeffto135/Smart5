def is_in_water(lat, lng):
    # 1. 西區水域 (堅尼地城/西營盤以北至西九龍以南)
    if 114.115 <= lng < 114.148:
        if 22.2875 <= lat <= 22.3020:
            return True
    # 2. 中區至尖沙咀主航道水域
    elif 114.148 <= lng < 114.175:
        if 22.2855 <= lat <= 22.2950:
            return True
    # 3. 灣仔/銅鑼灣至紅磡水域
    elif 114.175 <= lng < 114.188:
        if 22.2820 <= lat <= 22.2980:
            return True
    # 4. 北角至紅磡/啟德水域
    elif 114.188 <= lng < 114.215:
        if 22.2905 <= lat <= 22.2985:
            return True
    # 5. 鰂魚涌/筲箕灣至九龍灣水域
    elif 114.215 <= lng <= 114.235:
        if 22.2885 <= lat <= 22.3000:
            return True
    return False

all_meters = []
counter = 1

for dist in STREET_DATABASE:
    region = dist["region"]
    district = dist["district"]
    streets = dist["streets"]
    
    for s_info in streets:
        street_name, base_lat, base_lng, d_lat, d_lng = s_info
        
        num_clusters = 7
        for c in range(num_clusters):
            meter_id = f"HK-MTR-{str(counter).zfill(5)}"
            counter += 1
            
            offset_factor = (c - (num_clusters // 2)) * 0.4
            lat = round(base_lat + (d_lat * offset_factor), 6)
            lng = round(base_lng + (d_lng * offset_factor), 6)
            
            # 若偏移點位落入水域，自動校正回歸陸地
            if is_in_water(lat, lng):
                if region == "港島":
                    if lng < 114.175:
                        lat = 22.2840
                    elif lng < 114.188:
                        lat = 22.2785
                    else:
                        lat = 22.2880
                else:
                    lat = max(lat, 22.2985)
            
            total_spaces = 6 + ((counter * 7) % 15)
            is_full = (counter % 4 == 0)
            vacant_spaces = 0 if is_full else max(1, (counter * 11) % total_spaces)
            
            is_short = (counter % 5 == 0)
            max_dur = "30分鐘" if is_short else ("1小時" if counter % 3 == 0 else "2小時")
            
            if counter % 4 == 0:
                period = "全日 08:00 - 24:00"
            elif counter % 2 == 0:
                period = "星期一至六 08:00 - 24:00 (公眾假期除外)"
            else:
                period = "星期一至六 08:00 - 24:00；星期日及公眾假期 10:00 - 22:00"
                
            seg_name = f"(第 {c + 1} 段)"
            full_name = f"{district} {street_name} {seg_name}"
            
            all_meters.append({
                "meterId": meter_id,
                "streetName": full_name,
                "district": district,
                "region": region,
                "lat": lat,
                "lng": lng,
                "vacantSpaces": vacant_spaces,
                "totalSpaces": total_spaces,
                "chargingPeriod": period,
                "ratePer15Min": 2.0,
                "maxDuration": max_dur,
                "paymentMethods": ["八達通", "感應式信用卡", "轉數快", "快易通"],
                "lastUpdated": "剛剛更新"
            })

